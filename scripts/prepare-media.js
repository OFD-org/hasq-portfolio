import { readdir, mkdir, writeFile, access } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import ffmpeg from 'ffmpeg-static';
import probe from 'ffprobe-static';

const destination = 'assets/works/media';
await mkdir(destination, { recursive: true });
const groups = [
  ['2D & 3D_motion', 'motion', 'reels'],
  ['2D & 3D_motion/motion_edits (just-for-fun)', 'motion', 'experiments'],
  ['performance_creatives/creatives/videos', 'performance', 'ads'],
  ['performance_creatives/UI_animations(screen casts, outros)', 'performance', 'ui'],
  ['performance_creatives/creatives/static', 'performance', 'stills'],
  ['SaaS _ Brand content (in progress)', 'brand', 'brand'],
];
const titles = { '2D_showreel': '2D showreel', '2D_simple_edit': '2D motion edit', '3D_ad_campaign': '3D ad campaign', 'cs_edit_light': 'Counter-Strike edit', 'hunter_edit': 'Hunter edit', 'motion_edit1': 'Motion experiment', 'old_2024': 'Brand archive · 2024' };
const labels = { reels: 'Motion design', experiments: 'Personal exploration', ads: 'Performance creative', ui: 'UI animation', stills: 'Static creative', brand: 'SaaS / Brand' };
function run(binary, args) {
  const result = spawnSync(binary, args, { encoding: 'utf8', maxBuffer: 8 * 1024 * 1024 });
  if (result.status !== 0) throw new Error(result.stderr || result.error?.message);
  return result.stdout;
}
async function generate(path, args) {
  try { await access(path); } catch { run(ffmpeg, ['-hide_banner', '-loglevel', 'error', ...args, '-y', path]); }
}
const works = [];
for (const [directory, collection, kind] of groups) {
  const files = (await readdir(directory)).filter(file => /\.(mp4|mov|png)$/i.test(file)).sort((a,b) => a.localeCompare(b, undefined, { numeric: true }));
  for (const [index, file] of files.entries()) {
    const source = `${directory}/${file}`;
    const name = file.replace(/\.[^.]+$/, '');
    const id = `${kind}-${name}`;
    const isImage = file.endsWith('.png');
    const metadata = JSON.parse(run(probe.path, ['-v','error','-show_streams','-show_format','-of','json',source]));
    const stream = metadata.streams.find(item => item.codec_type === 'video');
    const duration = Number(metadata.format.duration || 0);
    const poster = `${destination}/${id}.jpg`;
    await generate(poster, [...(isImage ? [] : ['-ss', String(Math.min(2, duration / 4))]), '-i', source, '-frames:v','1','-vf',"scale=640:640:force_original_aspect_ratio=decrease",'-q:v','3']);
    const project = { id, collection, kind, title: titles[name] || `${labels[kind]} ${String(index + 1).padStart(2, '0')}`, category: labels[kind], poster, width: stream.width, height: stream.height };
    if (isImage) {
      project.image = `${destination}/${id}-full.jpg`;
      await generate(project.image, ['-i',source,'-frames:v','1','-q:v','2']);
    }
    else {
      project.duration = Math.round(duration);
      project.preview = `${destination}/${id}.mp4`;
      project.video = `${destination}/${id}-web.mp4`;
      await generate(project.preview, ['-ss',String(Math.min(1,duration / 4)),'-i',source,'-t','8','-an','-vf',"scale=640:640:force_original_aspect_ratio=decrease:force_divisible_by=2,fps=24",'-c:v','libx264','-preset','fast','-crf','27','-pix_fmt','yuv420p','-movflags','+faststart']);
      await generate(project.video, ['-i',source,'-vf',"scale=1280:1280:force_original_aspect_ratio=decrease:force_divisible_by=2,fps=30",'-c:v','libx264','-preset','fast','-crf','24','-maxrate','1800k','-bufsize','3600k','-pix_fmt','yuv420p','-c:a','aac','-b:a','128k','-movflags','+faststart']);
    }
    works.push(project);
    console.log(`${id}: ${stream.width}x${stream.height} ${project.duration || 'still'}`);
  }
}
await writeFile('js/data/works.js', '// Generated by scripts/prepare-media.js. Display titles belong in work-titles.js.\nexport const works = ' + JSON.stringify(works, null, 2) + ';\n');
console.log(`Prepared ${works.length} works.`);
